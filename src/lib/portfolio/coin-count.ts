import type {
  PortfolioCategory,
  SnapshotCompositionDto,
} from "@/lib/api/types";

/**
 * Счётчик монет категории — главная метрика Capital Growth (AGENTS.md §1:
 * «главная метрика — количество BTC и ETH, а не доллары»).
 *
 * --- Что чинится ---
 *
 * `snapshot_items.quantity` — величина ПРОИЗВОДНАЯ от цен: движок считает её
 * как (залог + вручную + свободные) в долларах, делённое на цену КАТЕГОРИИ
 * (coingecko «bitcoin» / «ethereum»). Каждое слагаемое при этом оценено по
 * СВОЕЙ цене — WBTC, cbBTC, wstETH, weETH торгуются своими парами. Числитель
 * и знаменатель живут независимо, и счётчик монет дрейфует на 0,1–0,3% в день
 * без единого действия владельца: гуляет спред обёрток к базовому активу,
 * LST растут к базовому активу по определению, цены токена и категории
 * прочитаны в разные моменты.
 *
 * Для стратегии накопления такая метрика бесполезна: по ней нельзя отличить
 * набор от шума. Отсюда правило ниже.
 *
 * --- Принятое правило: сумма монет по номиналу ---
 *
 * Количество категории = сумма количеств её токенов в единицах базового
 * актива, как есть: 1 wstETH считается за 1 ETH, 1 WBTC — за 1 BTC. Цены
 * в формулу не входят вообще, поэтому при неизменных количествах метрика
 * не меняется ни при каком движении рынка. Это и есть требуемый инвариант.
 *
 * Альтернатива — пересчитывать каждый токен через отношение его цены к цене
 * категории — отвергнута: это ровно текущая формула, разложенная по токенам,
 * то есть она возвращает тот самый дрейф, ради которого всё затевалось.
 * Точность ОЦЕНКИ эта метрика и не обслуживает: доллары стоят рядом
 * (`valueUsd`, `priceUsd`) и считаются по своим ценам, как и раньше.
 *
 * --- Чем за это платим, осознанно ---
 *
 * wstETH дороже ETH (~1,24 ETH за токен), поэтому счётчик ETH ЗАНИЖАЕТ
 * позицию. Размен приемлем по трём причинам:
 *
 *  1. Занижение статично. Оно меняется только когда владелец сам заворачивает
 *     или разворачивает актив — то есть на собственном действии, которое
 *     видно ступенькой и объяснимо. Дрейф же был ежедневным и невидимым,
 *     а именно его невозможно отделить от набора.
 *  2. Число сверяемо: его можно пересчитать, глядя в кошелёк. Эквивалент
 *     по курсу — нельзя.
 *  3. Долларовая оценка никуда не делась и показывается рядом, так что
 *     информация не теряется — теряется только смешение двух разных вопросов
 *     в одном числе.
 *
 * Рост баланса aToken от начисленных процентов счётчик, наоборот, показывает —
 * и правильно: токенов стало физически больше, это настоящий набор.
 *
 * --- Границы ---
 *
 * Заёмные свободные балансы в счётчик не входят: категории ведутся по
 * собственным средствам (Фаза 7, §10.1a). Неразмеченные входят — там
 * умолчание «своё».
 *
 * У стейблов единица — доллар: ручные записи вносятся уже в долларах,
 * а токены считаются по номиналу (1 USDC = $1). Депег в счётчике не виден
 * намеренно — он виден в стоимости.
 *
 * NULL ≠ 0. Состава нет (точка снята до его появления) — возвращаем null,
 * а не ноль: «не записали» и «монет не было» на графике накопления
 * выглядят одинаково катастрофически по-разному.
 */

/**
 * Безопасный разбор количества. Мусор — ноль, как в `toNumber` движка:
 * счётчик и стоимость должны спотыкаться об одни и те же данные одинаково.
 */
function toNumber(value: string): number {
  const n = Number.parseFloat(value);
  return Number.isFinite(n) ? n : 0;
}

/**
 * Количество монет категории по сырому составу снепшота.
 *
 * @param composition состав ОДНОЙ категории (`snapshot_items.composition`).
 *   null/undefined = состава в точке нет; результат — null.
 * @returns число в единицах категории (BTC / ETH / USD) либо null.
 */
export function coinCount(
  composition: SnapshotCompositionDto | null | undefined,
): number | null {
  if (!composition) return null;

  let total = 0;

  // Залог: по одному токену на строку, все — своей категории
  for (const c of composition.collateral) total += toNumber(c.quantity);

  // Ручные записи: btc/eth вносятся в монетах, stable — в долларах,
  // то есть обе уже в единицах категории
  for (const m of composition.manual) total += toNumber(m.amount);

  // Свободные балансы (Фаза 7). Поля может не быть вовсе — тогда точка
  // снята до чтения балансов, и залог с ручными записями были полным
  // составом своей эпохи: ровно то же множество слагаемых, из которого
  // в тот день складывалась и стоимость. Пустой суммой здесь ничего
  // не теряется.
  for (const f of composition.free ?? []) {
    // Заёмные в категорию не входят; null = не размечено = своё
    if (f.funds === "borrowed") continue;
    total += toNumber(f.quantity);
  }

  return total;
}

/**
 * Счётчик монет из строки снепшота, с явным указанием категории —
 * сахар для мест, где под рукой весь `items[]`.
 */
export function coinCountOf(
  items: readonly { category: PortfolioCategory; composition: SnapshotCompositionDto | null }[],
  category: PortfolioCategory,
): number | null {
  const item = items.find((i) => i.category === category);
  return item ? coinCount(item.composition) : null;
}
