import "server-only";
import { z } from "zod";

/**
 * Настройки пользователя: порог предупреждения по health factor (S4.1/S4.3)
 * и целевой LTV стратегии.
 *
 * Границы HF: строго больше 1 (порог ≤ 1 означал бы «предупреждать после
 * ликвидации») и не больше 10 (выше HF в осмысленных стратегиях не живет,
 * а опечатка вроде 15 вместо 1.5 превратила бы индикатор в вечную тревогу).
 *
 * Границы LTV: больше 0 (нулевая цель — это выход из стратегии, а не её
 * параметр) и не больше 90 (выше проходит порог ликвидации любого разумного
 * залога). Порог ликвидации сюда не входит: он приходит от протокола.
 */
// Сами значения — в универсальном модуле: их знает и клиент, пока
// /api/settings не ответил. Реэкспорт, чтобы серверный код не ходил в два места.
export {
  DEFAULT_HF_WARNING_THRESHOLD,
  DEFAULT_TARGET_LTV_PCT,
} from "@/lib/settings-defaults";

/**
 * Частичная схема: экран «Долг» правит только целевой LTV, «Настройки» —
 * только порог HF. Требовать оба поля значило бы заставлять каждый экран
 * знать и пересылать чужую настройку — и затирать её при гонке.
 */
export const settingsSchema = z
  .object({
    hfWarningThreshold: z
      .number()
      .gt(1, "Порог должен быть больше 1")
      .max(10, "Порог не больше 10"),
    targetLtvPct: z
      .number()
      .gt(0, "Целевой LTV должен быть больше 0")
      .max(90, "Целевой LTV не больше 90"),
  })
  .partial()
  .refine((v) => Object.keys(v).length > 0, {
    message: "Нечего сохранять",
  });

export type SettingsInput = z.infer<typeof settingsSchema>;
