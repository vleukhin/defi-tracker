/**
 * С какого момента кошелёк держит токен — чистое ядро, без сети.
 *
 * Приложение читает позицию балансом, а не историей, поэтому дата покупки
 * восстанавливается из переводов токена на кошелёк и с него. Ответ —
 * начало ТЕКУЩЕГО удержания: последний перевод, который поднял баланс
 * с нуля. Докупки его не сдвигают, а полный выход и повторный вход
 * начинают отсчёт заново.
 *
 * Почему не средневзвешенная дата по всем покупкам. Шкала отвечает на
 * вопрос «сколько я уже прошёл до погашения», и у позиции, собранной
 * несколькими покупками, честный ответ — «с первой из тех, что сейчас
 * лежат». Средняя дата сдвигала бы начало шкалы при каждой докупке, и
 * пройденная доля прыгала бы назад без единого движения рынка.
 *
 * Перевод с другого собственного кошелька — тоже поступление: приложение
 * не знает, какие адреса принадлежат одному владельцу на других сетях,
 * и не угадывает.
 */

export interface TokenTransfer {
  block: bigint;
  /** Позиция события в блоке — порядок внутри блока. */
  logIndex: number;
  direction: "in" | "out";
  amount: bigint;
  /** Время блока, секунды; null = источник не отдал, достаётся отдельно. */
  timestampSec: bigint | null;
}

/**
 * Перевод, с которого началось текущее удержание; null — баланс по истории
 * нулевой (история неполна или токен уже ушёл).
 *
 * Внутри одного события входящий обрабатывается раньше исходящего:
 * перевод самому себе приходит обеими сторонами, и при обратном порядке
 * баланс на мгновение обнулился бы и «начал» удержание заново.
 */
export function holdingStart(transfers: TokenTransfer[]): TokenTransfer | null {
  const ordered = [...transfers].sort(
    (a, b) =>
      (a.block < b.block ? -1 : a.block > b.block ? 1 : 0) ||
      a.logIndex - b.logIndex ||
      (a.direction === b.direction ? 0 : a.direction === "in" ? -1 : 1),
  );

  let balance = 0n;
  let start: TokenTransfer | null = null;
  for (const t of ordered) {
    const before = balance;
    balance += t.direction === "in" ? t.amount : -t.amount;
    // Отрицательный баланс — признак неполной истории; считаем его нулём,
    // иначе первое поступление после «дыры» не стало бы началом
    if (balance < 0n) balance = 0n;
    if (before <= 0n && balance > 0n) start = t;
    if (balance === 0n) start = null;
  }
  return balance > 0n ? start : null;
}
