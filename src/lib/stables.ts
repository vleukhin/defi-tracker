/**
 * Стейблкоины по символу — один список на все контуры.
 *
 * Нужен там, где важно «это доллар»: какие резервы Aave считать стоимостью
 * заемных стейблов и с какими депозитами ее вообще осмысленно сравнивать.
 * По стратегии (docs/07 §3) депозит на лендинге держат, только пока ставка
 * депозита выше ставки по займу, — сравнивать ставку депозита в ETH
 * со ставкой займа в USDC для этого правила бессмысленно.
 *
 * Евро-стейблы (EURC, EURS) сюда НЕ входят: доллар и евро — разные ставки
 * и разный риск, усреднять их в одно число нельзя.
 *
 * Модуль намеренно без "server-only": тем же списком пользуется интерфейс.
 */

/** Символы в верхнем регистре — как их отдают address book и резолверы. */
const STABLE_SYMBOLS = new Set([
  "USDC",
  "USDC.E",
  // USDCN — нативный USDC на Arbitrum/Optimism в терминах address book
  "USDCN",
  "USDBC",
  "USDT",
  "USDT0",
  // USD₮0 — символ USDT0 с типографским «₮» (так его пишет Fluid)
  "USD₮0",
  "DAI",
  "SDAI",
  "USDS",
  "SUSDS",
  "GHO",
  "LUSD",
  "FRAX",
  "SUSD",
  "CRVUSD",
  "PYUSD",
  "USDE",
  "SUSDE",
  "RLUSD",
  "MAI",
]);

/** Стейбл ли токен: сравнение по символу, регистр не важен. */
export function isStableSymbol(symbol: string): boolean {
  return STABLE_SYMBOLS.has(symbol.toUpperCase());
}
