/** Ручная запись — не протокол, и знака у неё нет: карандаш вместо марки. */
function ManualMark({ size }: { size: number }) {
  return <PencilLine size={size} strokeWidth={1.75} aria-hidden />;
}

const PROTOCOL_ICONS: Record<string, ProtocolIcon> = {
  uniswap: UniswapMark,
  aave: AaveMark,
  fluid: FluidMark,
  gmx: GmxMark,
  pendle: PendleMark,
  manual: ManualMark,
};

/**
 * Знак протокола или undefined — тогда плитка покажет аббревиатуру.
 * Незнакомый источник обязан рисоваться: читатель приносит строки,
 * про которые интерфейс ещё не знает.
 */
export function protocolIcon(
  protocol: string | null | undefined,
): ProtocolIcon | undefined {
  const key = protocolKey(protocol);
  return key === null ? undefined : PROTOCOL_ICONS[key];
}

/**
 * Плитка протокола со знаком — то, что стоит в шапке карточки позиции,
 * в списке «где работают заёмные» и в истории закрытых. Один вызов на
 * все три места: иначе где-то останется плитка без марки.
 */
export function ProtocolMark({
  protocol,
  size,
  className,
}: {
  /** Ключ протокола или значение из строки читателя (`uni_v3`, `gmx_v2`). */
  protocol: string | null | undefined;
  size?: number;
  className?: string;
}) {
  const brand = protocolBrand(protocol);
  return (
    <ProtocolTile
      abbr={brand.abbr}
      icon={protocolIcon(protocol)}
      color={brand.color}
      size={size}
      className={className}
    />
  );
}
