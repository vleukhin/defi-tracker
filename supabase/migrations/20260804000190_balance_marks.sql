-- =============================================================================
-- Свободные средства на кошельке и их разметка «свои / заемные».
--
-- До этой миграции приложение видело деньги в двух состояниях: залог в Aave
-- и размещенные позиции. Все остальное — монеты между займом и размещением,
-- остаток после частичного выхода из пула, газовый запас — существовало
-- только ручной записью, которую надо не забыть завести и поправить.
-- Теперь свободные балансы читаются из сети (chains/reader.ts, до сих пор
-- никем не вызывался), а эта таблица отвечает на второй вопрос стратегии:
-- ЧЬИ они. Заемные USDC, ждущие размещения, — не резерв Stability,
-- а капитал в пути в Yield (docs/07 §1-2).
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА В balances_cache.
-- Кэш принадлежит читателю: он его перезаписывает, а нулевые балансы удаляет
-- целиком (reader.ts, persistBalances). Разметка в кэше пережила бы один
-- вывод средств и погибла бы при следующем: вывели USDC в ноль — строка
-- удалена, вернули обратно — пометка «заемные» потеряна. Разметка живет
-- отдельно от показаний, ровно как position_marks живут отдельно от
-- protocol_positions.
--
-- ПОЧЕМУ КЛЮЧ ИМЕННО (user_id, wallet_id, chain, token).
-- Один и тот же токен в одной сети бывает своим на одном адресе и заемным
-- на другом — «заемные USDC на рабочем кошельке, свои на холодном» это
-- обычная ситуация, а не крайний случай. Кошелек при этом к сети не привязан
-- (один адрес читается на всех четырех), поэтому chain в ключе обязателен.
-- token = 'native' для монеты сети и lowercase-адрес контракта для ERC-20 —
-- так же, как в assets.contract_address.
--
-- ПОЧЕМУ funds NOT NULL, В ОТЛИЧИЕ ОТ position_marks.
-- Там строка держит пять независимых полей, и NULL означает «это поле
-- не сказали». Здесь поле одно, и сама строка И ЕСТЬ утверждение: нет
-- строки — «не размечено», есть — сказали что именно. Снять разметку =
-- удалить строку. Правило NULL <> 0 соблюдено: «не размечено» отличимо
-- от «заемные», и число неразмеченных выводится в сводке.
--
-- Решение по неразмеченным (утверждено): считаются СВОИМИ — деньги на
-- кошельке по умолчанию ваши, заемные там транзитны. Это расходится
-- с трактовкой позиций (там NULL идет в заемные), и расходится осознанно:
-- позиция по стратегии создается на заемные, а баланс кошелька — нет.
-- Обратное умолчание выкидывало бы свободный WBTC из главной метрики
-- стратегии до первой разметки.
--
-- FK на wallets с каскадом — то, чего не хватает position_marks: удалили
-- адрес, и разметка его балансов уходит вместе с ним, а не остается мусором.
-- user_id продублирован намеренно: RLS-политика тогда не делает join,
-- как и у всех остальных user-scoped таблиц.
--
-- chain_read_status здесь не трогается: source = 'erc20' разрешен там
-- с Фазы 5 (20260731000100_positions_phase5.sql).
-- =============================================================================

create table public.balance_marks (
  user_id    uuid not null references auth.users (id) on delete cascade,
  wallet_id  uuid not null references public.wallets (id) on delete cascade,
  chain      text not null check (chain in ('ethereum', 'arbitrum', 'base', 'optimism')),
  -- 'native' — монета сети; иначе адрес контракта в lowercase
  token      text not null check (token = 'native' or token ~ '^0x[0-9a-f]{40}$'),
  funds      text not null check (funds in ('own', 'borrowed')),
  updated_at timestamptz not null default now(),
  primary key (user_id, wallet_id, chain, token)
);

-- «Вся разметка кошелька» — горячий путь загрузки портфеля; первичный ключ
-- начинается с user_id и такую выборку не покрывает
create index balance_marks_wallet_idx on public.balance_marks (wallet_id);

alter table public.balance_marks enable row level security;

create policy "balance_marks: owner full access"
  on public.balance_marks
  for all
  to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

comment on table public.balance_marks is
  'Разметка свободных средств кошелька: свои или заемные. Ключ натуральный '
  '(кошелек, сеть, токен) — показания читателя в balances_cache '
  'пересоздаются и удаляются при нулевом балансе, разметка это переживает.';

comment on column public.balance_marks.funds is
  'own = собственные, borrowed = заемные. ОТСУТСТВИЕ СТРОКИ = «не размечено», '
  'и это не то же самое, что own: неразмеченные считаются своими в категориях, '
  'но пересчитываются отдельно и помечаются в интерфейсе.';

-- -----------------------------------------------------------------------------
-- snapshots.free_usd / snapshot_items.free_usd: свободные средства на дату.
--
-- Пишутся по той же причине, что debt_usd и positions_usd: величина
-- невосстановима задним числом. Баланс кошелька на прошлую дату достала бы
-- разве что archive-нода, а разметку «свои/заемные» на тот момент — уже
-- ничто: она перезаписывается на месте.
--
-- Полезны и сразу: в день включения чтения балансов total_usd шагнет вверх,
-- и это реальный рост учитываемых активов, а не переоценка. Отдельная
-- колонка позволяет объяснить ступеньку числом, а не памятью.
--
-- NULL, а не DEFAULT 0, в обеих колонках: снепшоты, снятые до этой миграции,
-- свободных средств не знали, и ноль в них означал бы «свободных не было».
-- -----------------------------------------------------------------------------
alter table public.snapshots
  add column if not exists free_usd numeric;

alter table public.snapshot_items
  add column if not exists free_usd numeric;

comment on column public.snapshots.free_usd is
  'Свободные средства на кошельках (свои и неразмеченные) на момент съема. '
  'NULL = снепшот снят до того, как балансы начали читаться.';

comment on column public.snapshot_items.free_usd is
  'Свободные средства этой категории. NULL = снепшот снят до чтения балансов.';

-- =============================================================================
-- GRANT'ы: auto_expose_new_tables = off, без них новая таблица недоступна
-- даже при правильной RLS-политике.
-- =============================================================================

grant all on public.balance_marks to service_role;
grant select, insert, update, delete on public.balance_marks to authenticated;
