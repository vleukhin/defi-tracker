-- =============================================================================
-- Целевой LTV — уровень, к которому стратегия возвращает плечо (docs/07 §10.3:
-- «Целевой LTV 50%» числился в разрыве как «частично»: утилизация на экране
-- была, но цель нигде не задавалась и отклонение не подсвечивалось).
--
-- Почему настройка, а не константа: 50% — рабочее значение из стратегии, но
-- оно двигается вместе с риск-аппетитом и с тем, какой залог лежит в Growth.
-- Порог предупреждения HF рядом уже живёт настройкой, и цель LTV с ним
-- связана: одно ограничивает риск снизу, другое задаёт рабочую точку.
--
-- Границы: строго больше 0 (нулевая цель означала бы «погасить весь долг»,
-- а это выход из стратегии, а не её параметр) и не больше 90 — выше проходит
-- порог ликвидации любого разумного залога, и цель за ним значила бы
-- «стремиться к ликвидации».
-- =============================================================================

alter table public.user_settings
  add column if not exists target_ltv_pct numeric not null default 50
    check (target_ltv_pct > 0 and target_ltv_pct <= 90);

comment on column public.user_settings.target_ltv_pct is
  'Целевой LTV в процентах: долг / залог, к которому выравнивается плечо. '
  'По умолчанию 50 — рабочее значение стратегии Capital Growth. '
  'Не путать с порогом ликвидации: тот приходит от протокола и не '
  'настраивается, а этот — намерение пользователя.';
