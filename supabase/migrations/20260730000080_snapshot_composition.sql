-- Сырой состав категории в снепшоте.
--
-- Зачем: доллары на прошлую дату восстановимы из исторической цены, а
-- количество монет — нет. При этом snapshot_items.quantity — величина
-- ПРОИЗВОДНАЯ (стоимость / цена категории, то есть BTC/ETH-эквивалент):
--   * при отсутствии цены она равна null, и день теряет счетчик монет;
--   * агрегат не помнит, из чего сложен — сколько было WBTC, сколько
--     wstETH, сколько внесено вручную.
--
-- Для стратегии накопления динамика количества монет важнее кривой
-- стоимости, поэтому пишем сырые количества: они ни от каких цен не
-- зависят и позволяют пересчитать любой эквивалент задним числом.
--
-- Формат composition:
--   {
--     "collateral": [{"symbol":"WBTC","chain":"ethereum","quantity":"72.607"}],
--     "manual":     [{"label":"GMX пул","amount":"15000"}]
--   }
-- Количества строками — numeric не теряет точность через JSON.

alter table public.snapshot_items
  add column if not exists composition jsonb;

comment on column public.snapshot_items.composition is
  'Сырые количества монет на дату: залог по токенам/сетям и ручные записи. Не зависит от цен — в отличие от quantity.';
