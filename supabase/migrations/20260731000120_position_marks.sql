-- =============================================================================
-- Фаза 6, уточнение модели: доля собственных средств указывается У ПОЗИЦИИ.
--
-- Почему журнал own_capital_placements не подошел. Он отвечал на вопрос
-- «сколько всего своих денег внутри позиций», но не на вопрос «в какой
-- именно позиции». По стратегии собственные стейблы ВСЕГДА распределены
-- по позициям зон Yield и Stability, поэтому разнести их по зонам одной
-- общей суммой нельзя: она не знает, куда попала.
--
-- Отсюда две правки:
--   1. position_zones -> position_marks: таблица теперь хранит не только
--      зону, но и own_usd. Ключ прежний — натуральный (протокол, сеть,
--      external_id), чтобы разметка пережила пересоздание строки читателем
--      и новый tokenId после перезаливки диапазона CLMM.
--   2. own_capital_placements удаляется: сумма выводится из пометок.
--
-- Категория «Стейблы» после этого складывается из собственных долей позиций
-- плюс свободные стейблы, а не вводится одним числом.
-- =============================================================================

alter table public.position_zones rename to position_marks;

-- -----------------------------------------------------------------------------
-- own_usd: сколько СОБСТВЕННЫХ средств в позиции; остальное заемное.
--
-- NULL = «не размечено», и это НЕ ноль. Ноль — осмысленное утверждение
-- «своих здесь нет, позиция целиком на заемные». Различать обязательно:
-- после каждой перезаливки CLMM позиция приходит неразмеченной, и молча
-- считать ее нулем, не показав этого, значит занижать собственные средства.
--
-- Решение по неразмеченным (утверждено): в расчет идут как заемные, но
-- в интерфейсе помечаются, и в сводке выводится их число.
-- -----------------------------------------------------------------------------
alter table public.position_marks
  add column if not exists own_usd numeric
    check (own_usd is null or own_usd >= 0);

-- Зона тоже становится необязательной: пометка может задавать только own_usd
alter table public.position_marks
  alter column zone drop not null;

comment on table public.position_marks is
  'Пользовательская разметка позиции: зона стратегии и доля собственных '
  'средств. Ключ натуральный, а не id строки protocol_positions: читатели '
  'пересоздают строки, а CLMM при перезаливке выдает новый tokenId.';

comment on column public.position_marks.own_usd is
  'Сколько собственных средств в позиции. NULL = не размечено (НЕ ноль). '
  'Ноль означает «позиция целиком на заемные».';

-- -----------------------------------------------------------------------------
-- own_capital_placements больше не нужен: величина выводится из пометок.
-- Таблица заведена в этой же фазе и данных нигде не содержит.
-- -----------------------------------------------------------------------------
drop table if exists public.own_capital_placements;

grant all on public.position_marks to service_role;
grant select, insert, update, delete on public.position_marks to authenticated;
