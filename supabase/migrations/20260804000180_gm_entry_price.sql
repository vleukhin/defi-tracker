-- =============================================================================
-- Точка отсчёта падения у GM-пула (docs/07 §5, §7).
--
-- Уровни действий −7 / −15 / −30 / −50 / −70% стратегия считает не от текущей
-- цены и не от максимума, а от ПОДВИЖНОЙ точки отсчёта: цены базового актива
-- на момент сборки портфеля, переносимой вперёд после того, как на росте LTV
-- довели до 50%. Без этого числа уровни не от чего считать, и карточка GM
-- отвечала только на вопросы про выведенное и долю среди пулов (§10.3).
--
-- Хранится у позиции, а не в user_settings: точка отсчёта переносится
-- по каждому пулу отдельно (продали GM на уровне — купили заново уже
-- по другой цене), и общее число на портфель эту историю не выражает.
-- Цена — в единицах базового актива рынка: у GM BTC/USDC это цена BTC,
-- у GM ETH/USDC — цена ETH.
--
-- NULL = «точка отсчёта не задана», и уровни не считаются вовсе. Ноль здесь
-- запрещён отдельной проверкой: от нуля падение не считается — это не «нет
-- данных», а деление на ноль.
-- =============================================================================

alter table public.position_marks
  add column if not exists entry_price_usd numeric
    check (entry_price_usd is null or entry_price_usd > 0);

comment on column public.position_marks.entry_price_usd is
  'Точка отсчёта падения: цена базового актива рынка на момент входа в пул. '
  'От неё считаются уровни −7 / −15 / −30 / −50 / −70 (docs/07 §5). '
  'NULL = не задана, уровни не считаются. Ноль запрещён: от него падения нет.';
