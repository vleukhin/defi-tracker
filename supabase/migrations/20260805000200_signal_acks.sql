-- =============================================================================
-- Отметки «действие выполнено» для ленты сигналов.
--
-- Лента показывает уровень падения GM, пока цена ниже него, и срок CLMM,
-- пока позиция вне диапазона. Само по себе это честно: приложение видит
-- только текущую цену и состав пула, а выполнил ли владелец продажу — нет.
-- Но после выполненной операции сигнал превращается в шум, и висит он не
-- час, а до разворота рынка.
--
-- Отсюда таблица: единственное, чего приложению не хватает, — сказанного
-- вслух «я это сделал». Вывести из данных этот факт нельзя. Продажа 30% GM
-- на уровне −7% меняет стоимость позиции, но ровно так же её меняет и
-- падение цены; withdrawnUsd растёт и при выводе на прошлом уровне.
--
-- ПОЧЕМУ КЛЮЧ НАТУРАЛЬНЫЙ, А НЕ id ПОЗИЦИИ. По той же причине, что
-- у position_marks и balance_marks: читатели пересоздают строки
-- protocol_positions, а CLMM при перезаливке диапазона выдаёт новый tokenId.
-- signal_key собирается из вида сигнала и zone_key позиции — «gm-level:
-- gmx_v2:arbitrum:0x…:15», и переживает пересчёт.
--
-- ПОЧЕМУ ОТДЕЛЬНОЙ КОЛОНКОЙ ЛЕЖИТ ОТПЕЧАТОК ОБСТАНОВКИ. Отметка относится
-- не к сигналу вообще, а к конкретному решению. Что делает её недействительной
-- (решение владельца):
--
--   * НОВЫЙ УРОВЕНЬ. Уровни −7 и −15 — разные ключи, поэтому отметка на −7
--     не молчит про −15 сама собой, без всяких правил.
--   * НОВАЯ ТОЧКА ОТСЧЁТА. Она подвижна (docs/07 §7): после доведения LTV
--     до 50% на росте её переносят, и прежние уровни считаются заново от
--     новой цены. Отметка, поставленная от старой точки, к новым уровням
--     отношения не имеет. Поэтому у GM отпечаток — цена входа.
--   * НОВЫЙ ВЫХОД ИЗ ДИАПАЗОНА. У CLMM отпечаток — момент выхода
--     (out_of_range_since): позиция вернулась в диапазон и вышла снова —
--     это другое ожидание и другое решение, а не то же самое.
--
-- Время в правила не входит намеренно: срок не меняет того, выполнено
-- действие или нет, а отметка со сроком годности тихо вернула бы сигнал,
-- на который владелец уже ответил.
--
-- ОТМЕЧАТЬ МОЖНО НЕ ВСЁ. Ручку ограничивает не эта таблица, а роут: отмечают
-- уровни GM и вышедший срок CLMM — там, где стратегия предписывает разовую
-- операцию. Риск ликвидации не отмечается вовсе: HF — не задача к исполнению,
-- а состояние, и скрыть его значило бы разрешить не видеть единственный
-- сценарий, способный принудительно прервать накопление (docs/03 §S4.3).
-- Гигиена данных не отмечается потому, что гаснет сама, когда данные
-- починены; отметка на «нет разметки» прятала бы проблему вместо решения.
--
-- Строка не удаляется при возврате сигнала: она перестаёт совпадать
-- отпечатком, и этого достаточно. Снятие отметки владельцем — delete.
-- =============================================================================

create table public.signal_acks (
  user_id     uuid not null references auth.users (id) on delete cascade,
  -- Вид сигнала и натуральный ключ его предмета: «gm-level:<zone_key>:15»
  signal_key  text not null check (length(signal_key) between 1 and 200),
  -- Обстановка, к которой относится отметка: цена входа у GM, момент выхода
  -- из диапазона у CLMM. Сменилась — отметка больше не про это решение
  fingerprint text not null check (length(fingerprint) between 1 and 100),
  acked_at    timestamptz not null default now(),
  primary key (user_id, signal_key)
);

alter table public.signal_acks enable row level security;

create policy "signal_acks: owner full access"
  on public.signal_acks
  for all
  to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

comment on table public.signal_acks is
  'Отметки «действие по сигналу выполнено». Ключ натуральный (вид сигнала + '
  'zone_key позиции) — переживает пересоздание protocol_positions читателем '
  'и смену tokenId при перезаливке CLMM.';

comment on column public.signal_acks.fingerprint is
  'Отпечаток обстановки на момент отметки: цена входа у GM-пула, момент '
  'выхода из диапазона у CLMM. Не совпал с текущим — сигнал возвращается '
  'в ленту, потому что решение теперь другое.';

-- =============================================================================
-- GRANT'ы: auto_expose_new_tables = off, без них таблица недоступна даже
-- при правильной RLS-политике.
-- =============================================================================

grant all on public.signal_acks to service_role;
grant select, insert, update, delete on public.signal_acks to authenticated;
