-- =============================================================================
-- Фаза 6, уточнение: из позиции капитал не только заходит, но и выходит.
--
-- Пробел предыдущей версии: доход считался как «стоимость − вложено», то есть
-- предполагалось, что вложенное остается в позиции до конца. По стратегии это
-- неверно: на падении GM-пулы частично продаются, полученные BTC/ETH уходят
-- в залог Growth Zone, и позиция становится дешевле — но не потому, что
-- капитал потерян, а потому что он переехал.
--
-- Без учета выводов вложенные в GM 20 800 заемных при текущей стоимости
-- 8 046 показали бы убыток 12 754, хотя разница почти целиком лежит
-- в залоге в виде BTC и ETH.
--
--   доход = стоимость + выведено − вложено
--
-- Выведенное в «Активы» второй раз не попадает: BTC и ETH уже посчитаны
-- залогом. Величина нужна только для честного расчета доходности позиции.
-- =============================================================================

alter table public.position_marks
  add column if not exists withdrawn_usd numeric
    check (withdrawn_usd is null or withdrawn_usd >= 0);

comment on column public.position_marks.withdrawn_usd is
  'Сколько выведено из позиции — по стоимости на момент вывода. Нужно, '
  'чтобы продажа части GM с переводом BTC/ETH в залог не выглядела убытком. '
  'NULL = не указано; в расчете дохода трактуется как ноль, потому что '
  'отсутствие выводов — обычное состояние позиции.';
