-- =============================================================================
-- snapshots.free_borrowed_usd: свободные ЗАЕМНЫЕ средства на дату съема.
--
-- ДЫРА, КОТОРУЮ ЗАКРЫВАЕТ МИГРАЦИЯ. С Фазы 7 Активы складываются из трех
-- слагаемых (overview.ts): портфель + размещенные позиции + свободные заемные
-- на кошельках. В снепшот попадали только два первых: buildSnapshotRows
-- получал freeBorrowedUsd в SnapshotSource и не использовал его ни разу.
-- В total_usd заемных нет (три категории ведутся по собственным средствам),
-- в free_usd их тоже нет (там свои и неразмеченные) — собрать Активы точки
-- истории было не из чего.
--
-- Это ровно та ошибка, на которой обожглась Фаза 5: Долг вычитается целиком,
-- а часть Активов в формулу не входит, и Чистая занижена на всю занятую, но
-- еще не размещенную сумму. На текущем экране она исправлена; в истории
-- воспроизводилась бы каждый день, и график Прибыли рисовал бы провал в день
-- займа и скачок в день размещения — движения, которых не было.
--
-- NULL, А НЕ DEFAULT 0. Точка, снятая до этой миграции, о заемных свободных
-- не знала, и ноль в ней означал бы «занятых денег на кошельке не было».
-- Развилка та же, что у free_usd: кошельков нет — честный ноль; кошельки
-- есть, а балансы не читались — NULL.
--
-- АСИММЕТРИЯ С PortfolioOverviewDto.freeBorrowedUsd (там number, не nullable)
-- намеренная. На текущем экране баланс без цены дает warning в строке
-- категории, а не делает Активы неизвестными: сеть можно перечитать сейчас.
-- Прошлую дату перечитать нельзя, поэтому здесь «не читалось» обязано быть
-- отличимо от нуля.
--
-- ЗАДНИМ ЧИСЛОМ НЕ ВОССТАНАВЛИВАЕТСЯ, и попытки здесь нет. Состав
-- (snapshot_items.composition.free) пишется только с 20260804000190 и несет
-- количество и разметку «свои/заемные», но не цену токена; price_usd рядом —
-- цена КАТЕГОРИИ, а свободный wstETH это не 1 ETH. Точно восстановились бы
-- одни стейблы (цена фиксирована 1.00) и всего за два дня — приблизительное
-- число в слагаемом Активов ничем не лучше честного NULL.
--
-- Grant'ы не трогаются: права выданы на таблицу целиком (20260730000030,
-- пересозданы в 20260730000070) и покрывают новые колонки.
-- =============================================================================

alter table public.snapshots
  add column if not exists free_borrowed_usd numeric
    check (free_borrowed_usd is null or free_borrowed_usd >= 0);

comment on column public.snapshots.free_borrowed_usd is
  'Свободные ЗАЕМНЫЕ средства на кошельках на момент съема. В total_usd '
  'и free_usd не входят (те ведутся по собственным средствам), в Активы '
  'точки входят целиком. NULL = балансы на эту дату не читались.';

-- Комментарий positions_usd (20260731000100) описывал Активы точки двумя
-- слагаемыми — с этой миграции их три
comment on column public.snapshots.positions_usd is
  'Размещенные позиции (Fluid после неттинга + GM + LP) на момент съема. '
  'Активы точки = total_usd + positions_usd + free_borrowed_usd. '
  'NULL = не было известно.';
