-- =============================================================================
-- История закрытых позиций: журнал исчезновений вместо тихого delete.
--
-- ПРОБЕЛ. Позиция существует ровно столько, сколько её видит читатель цепочки.
-- Все четыре читателя размещений в конце записи делают сборку мусора: удаляют
-- из protocol_positions строки, которых в ответе сети нет. Удалённые строки
-- запрос выбрасывает, и от закрытой позиции не остаётся ничего — ни последней
-- стоимости, ни состава LP, ни цены оракула GM на тот момент. Восстановить их
-- потом нельзя ни из какого источника: тот же довод уже записан в
-- 20260731000100 про snapshots.positions_usd — «Не сняли — потеряли навсегда».
-- Между тем выходы по стратегии штатны: CLMM перезаливается при выходе из
-- диапазона (docs/07 §5), PT погашается в срок, GM-пулы продаются по уровням.
-- На вопрос «что у меня было и чем кончилось» приложение не отвечало вовсе.
--
-- ПОЧЕМУ НЕ КОЛОНКА closed_at В protocol_positions. Эти строки принадлежат
-- читателю: он их пересоздаёт при каждом обновлении, а CLMM при перезаливке
-- выдаёт новый tokenId. Флаг на машинной строке живёт до следующего upsert.
--
-- ПОЧЕМУ НЕ КОЛОНКА В position_marks. Ключ там натуральный, и это осознанно:
-- разметка обязана переживать пересоздание строки. Но Fluid (адрес fToken),
-- Pendle (адрес токена) и GMX (адрес рынка) при повторном входе в ТОТ ЖЕ
-- рынок переиспользуют тот же ключ — повторный вход затёр бы прошлое
-- закрытие. У CLMM ключ каждый раз новый, но на одно это полагаться нельзя:
-- три протокола из четырёх ведут себя иначе.
--
-- ПОЧЕМУ КЛЮЧ СУРРОГАТНЫЙ. Закрытий одного рынка бывает много, и это разные
-- события — вошёл, вышел, вошёл снова. Тот же выбор, что у gm_level_actions
-- (id uuid, а не пара «пользователь + уровень»), и по той же причине.
--
-- ПОЧЕМУ РАЗМЕТКА КОПИРУЕТСЯ, А НЕ ЧИТАЕТСЯ ССЫЛКОЙ. Из предыдущего: при
-- повторном входе position_marks перезаписывается, и закрытая позиция
-- показала бы вложенное от следующей. Снимок на момент закрытия — это
-- единственная величина, которая останется верной.
--
-- ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Фактической выручки от выхода. Приложение видит
-- последнее успешное показание, а не сумму сделки, и выдать одно за другое
-- значило бы соврать в единственном месте, где этот итог вообще записан.
-- Отсюда имя колонки last_value_usd, а не proceeds_usd или exit_value_usd:
-- имя обязано говорить, что это показание.
--
-- ПОЧЕМУ СТОИМОСТЬ И ПОДПИСЬ ПИШУТСЯ, А НЕ ВЫВОДЯТСЯ НА ПОКАЗЕ.
-- protocol_positions.value_usd заполнен только у GM-пулов: их цену отдаёт
-- оракул GMX. У Fluid, CLMM и Pendle стоимость считается при показе из
-- payload, decimals и цены актива, а в кэше лежит null. Скопировать
-- value_usd в архив значило бы получить прочерк у трёх протоколов из
-- четырёх. Поэтому закрытие считает стоимость тем же buildPositions, что
-- и живой экран, и кладёт результат — последнее, что приложение видело.
-- Подпись (title/subtitle) рождается там же и тоже сохраняется: правила её
-- построения меняются вместе с кодом, а запись о закрытии должна остаться
-- такой, какой её увидели.
--
-- ПОЧЕМУ НЕТ КОЛОНКИ profit_usd. Она выводится из last_value_usd,
-- withdrawn_usd и вложенного — то есть была бы вторым носителем одного
-- факта. На этом проект уже обжигался (docs/07 §10.1), и правило держится:
-- один факт — один носитель.
-- =============================================================================

create table public.closed_positions (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references auth.users (id) on delete cascade,
  -- Кошелёк нужен и после закрытия: «в каком кошельке это было» — такой же
  -- вопрос владельца, как «в каком протоколе». Каскад от wallets намеренный:
  -- удалённый кошелёк уносит свою историю, иначе записи ссылались бы в пустоту
  wallet_id   uuid not null references public.wallets (id) on delete cascade,
  -- Только протоколы размещения: Aave здесь не бывает. Залог и долг — это не
  -- позиция, которую закрывают, а состояние сети, и список значений повторяет
  -- position_marks_protocol_check, а не protocol_positions_protocol_check
  protocol    text not null check (protocol in ('fluid', 'gmx_v2', 'uni_v3', 'pendle')),
  chain       text not null check (chain in ('ethereum', 'arbitrum', 'base', 'optimism')),
  external_id text not null check (length(external_id) between 1 and 200),

  -- Подпись позиции на момент закрытия: «fUSDC», «GM ETH», «WETH/USDC 0,05%»
  title    text not null check (length(title) between 1 and 200),
  subtitle text check (subtitle is null or length(subtitle) between 1 and 200),

  -- Последнее показание читателя
  last_value_usd numeric,
  last_quantity  numeric,
  payload        jsonb,
  last_read_at   timestamptz not null,
  closed_at      timestamptz not null default now(),

  -- Снимок разметки на момент закрытия
  zone                   text    check (zone is null or zone in ('growth', 'yield', 'stability')),
  own_principal_usd      numeric check (own_principal_usd is null or own_principal_usd >= 0),
  borrowed_principal_usd numeric check (borrowed_principal_usd is null or borrowed_principal_usd >= 0),
  withdrawn_usd          numeric check (withdrawn_usd is null or withdrawn_usd >= 0),
  entry_price_usd        numeric check (entry_price_usd is null or entry_price_usd > 0),

  created_at timestamptz not null default now(),

  -- ИДЕМПОТЕНТНОСТЬ ДЕРЖИТСЯ БАЗОЙ, А НЕ ДЕДУПЛИКАЦИЕЙ В КОДЕ. Записывающий
  -- путь сначала пишет закрытие, потом удаляет строку позиции: упади удаление,
  -- следующее обновление повторит вставку, и повтор обязан погаснуть сам.
  -- У обречённой строки updated_at фиксирован, поэтому тот же самый случай
  -- закрытия сталкивается сам с собой. Повторный вход в тот же рынок приходит
  -- с другим updated_at и ложится отдельной строкой — это другое событие,
  -- и слить их было бы потерей истории.
  unique (user_id, protocol, chain, external_id, last_read_at)
);

-- Горячий путь — «все закрытия, свежие первыми». Тайбрейк по id обязателен
-- по той же причине, что в gm_reference_points: now() в default — время
-- НАЧАЛА ТРАНЗАКЦИИ, а одно обновление закрывает позиции пачкой, и все они
-- получают ровно один closed_at. Без второго ключа порядок внутри пачки
-- зависел бы от плана запроса.
create index closed_positions_user_closed_idx
  on public.closed_positions (user_id, closed_at desc, id desc);

comment on table public.closed_positions is
  'Журнал закрытых позиций размещения. Запись создаётся автоматически в момент, '
  'когда позиция исчезла из успешного чтения цепочки. Строки принадлежат '
  'пользователю, а не читателю: читатель их не пересоздаёт и не удаляет.';

comment on column public.closed_positions.last_value_usd is
  'Стоимость по последнему успешному показанию, посчитанная тем же кодом, '
  'что на живом экране (buildPositions): в кэше у Fluid, CLMM и Pendle её '
  'нет вовсе. ЭТО НЕ ВЫРУЧКА от выхода: сумму сделки приложение не видит. '
  'NULL = стоимость не была известна и тогда — не было цены актива или '
  'не разобрался payload, — и это НЕ «закрылась в ноль».';

comment on column public.closed_positions.title is
  'Снимок подписи позиции на момент закрытия. Копия, а не вычисление на '
  'показе: правила построения подписи меняются вместе с кодом, а запись '
  'о закрытии должна остаться такой, какой её увидели.';

comment on column public.closed_positions.last_quantity is
  'Количество в единицах позиции на момент последнего чтения; у LP это '
  'ликвидность. NULL = не было записано.';

comment on column public.closed_positions.payload is
  'Снимок payload удалённой строки: состав LP, тики диапазона, имя рынка, '
  'дата погашения. Нужен для подписи позиции в архиве и для диагностики — '
  'задним числом эти величины невосстановимы.';

comment on column public.closed_positions.last_read_at is
  'protocol_positions.updated_at удалённой строки: на ЭТУ дату верна '
  'стоимость. Отдельно от closed_at, потому что это разные моменты — '
  'показание могло быть снято за сутки до того, как исчезновение заметили.';

comment on column public.closed_positions.closed_at is
  'Когда исчезновение ЗАМЕЧЕНО очередным обновлением. Момент закрытия на '
  'цепочке приложению неизвестен в принципе: оно видит не транзакцию, '
  'а отсутствие баланса, — и подставить его сюда значило бы соврать.';

comment on column public.closed_positions.zone is
  'Зона стратегии из разметки на момент закрытия. NULL = зона не была задана; '
  'умолчание протокола (включая PT -> Stability) подставляет сборка на чтении, '
  'а не база: умолчание — это трактовка, и место ей в одном слое.';

comment on column public.closed_positions.own_principal_usd is
  'Снимок «вложено своих» на момент закрытия. NULL = не было размечено, '
  'и это НЕ ноль: ноль означал бы «своих здесь не было».';

comment on column public.closed_positions.borrowed_principal_usd is
  'Снимок «вложено заёмных». NULL = не было размечено. Доход считается только '
  'когда размечены ОБЕ половины вложенного: иначе непонятно, доход перед нами '
  'или незаявленная заёмная доля.';

comment on column public.closed_positions.withdrawn_usd is
  'Снимок «выведено из позиции» по стоимости на момент вывода. В расчёте '
  'итога NULL трактуется как ноль — отсутствие выводов обычное состояние.';

comment on column public.closed_positions.entry_price_usd is
  'Снимок точки отсчёта падения (docs/07 §5, §7) — осмысленна у GM-пулов. '
  'NULL = не была задана. Журнал переносов gm_reference_points при закрытии '
  'не копируется: он живёт своей жизнью и переживает удаление позиции.';

alter table public.closed_positions enable row level security;

create policy "closed_positions: owner full access"
  on public.closed_positions
  for all
  to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

