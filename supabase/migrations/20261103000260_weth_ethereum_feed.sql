-- WETH в справочнике assets — на фид "ethereum", как во всех остальных путях.
--
-- Коммит 11da395 перевел WETH на "ethereum" в коде (prices/symbol-coingecko.ts,
-- chains/allowlist.ts, chains/aave.ts), но справочник assets остался на "weth":
-- сид 20260730000010 к тому моменту уже был применен, а перегенерация сида
-- задним числом в существующую базу не попадает. Обоснование самого правила
-- (обертка держит ETH 1:1 контрактом) — в prices/symbol-coingecko.ts.
--
-- Последствия расхождения были двумя сразу:
--   1) свободный WETH оценивался по фиду "weth", а не по цене категории —
--      тот самый дрейф, который 11da395 должен был убрать;
--   2) POST /api/refresh берет id цены из allowlist ("ethereum") и фид "weth"
--      не запрашивает вовсе, а экран портфеля берет его из assets. Цена "weth"
--      обновлялась только ночным снепшотом, и метка «цены N ч назад» не уходила
--      по кнопке обновления.
--
-- Строка "weth" в coin_prices не удаляется: кэш цен — показания, а не
-- конфигурация, и без запросов она просто перестает читаться.
-- =============================================================================

update public.assets
set coingecko_id = 'ethereum'
where symbol = 'WETH'
  and coingecko_id = 'weth';
