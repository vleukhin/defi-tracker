-- =============================================================================
-- snapshots.collateral_usd и snapshots.health_factor: залог и health factor
-- на дату съема — основа истории HF и LTV на экране «Долг».
--
-- ЧЕГО НЕ ХВАТАЛО. Долг в снепшоте есть с Фазы 4 (debt_usd), а второй
-- половины отношения — залога — нет. Поэтому LTV точки истории не считался
-- вовсе, а HF не хранился нигде: aave_account_health перезаписывается
-- каждые 15 минут кроном здоровья, hf_alert_state держит только последнее
-- УВЕДОМЛЕННОЕ значение и намеренно не двигается, когда ничего не произошло.
-- Оба числа задним числом невосстановимы: ни цены оракула Aave на прошлую
-- дату, ни состава залога с его LT у нас нет.
--
-- ПОЧЕМУ ЗАЛОГ ОТДЕЛЬНОЙ КОЛОНКОЙ, А НЕ ИЗ snapshot_items.collateral_usd.
-- Там залог оценен по CoinGecko и разложен по трем категориям портфеля;
-- здесь — totals оракула Aave, тот же базис, что у debt_usd. Делить долг
-- по одному базису на залог по другому значило бы получать LTV, который
-- не сходится ни с приложением, ни с самим Aave. Небольшое расхождение
-- базисов принято осознанно еще в 20260730000090 — но внутри одной дроби
-- базис обязан быть один.
--
-- HEALTH FACTOR — МИНИМУМ ПО (кошелек, сеть), а не среднее и не пересчет
-- из сумм. Ликвидация приходит к худшей позиции, а не к портфелю в среднем:
-- то же правило, по которому считается minHealthFactor на экране «Долг»
-- (lib/api/debt.ts) и по которому срабатывают уведомления.
--
-- NULL У HEALTH_FACTOR ДВУЗНАЧЕН, И ЭТО НАМЕРЕННО. Как и в
-- aave_account_health, NULL означает «долга нет» («∞» — фейковое огромное
-- число не хранится никогда). Отличить это от «не читалось» позволяет
-- соседняя колонка: debt_usd = 0 — долга действительно не было;
-- debt_usd IS NULL — здоровье в тот день не читалось. Отдельный флаг был бы
-- третьим способом сказать то, что уже сказано двумя колонками.
--
-- collateral_usd IS NULL = залог на эту дату не читался. Ноль означал бы
-- «залога не было» и дал бы LTV с делением на ноль — читатель обязан
-- различать эти случаи.
--
-- ЗАДНИМ ЧИСЛОМ НЕ ЗАПОЛНЯЕТСЯ: у точек до этой миграции истории HF и LTV
-- не будет, они останутся разрывами. Придумать им значение неоткуда.
-- =============================================================================

alter table public.snapshots
  add column if not exists collateral_usd numeric
    check (collateral_usd is null or collateral_usd >= 0);

alter table public.snapshots
  add column if not exists health_factor numeric
    check (health_factor is null or health_factor >= 0);

comment on column public.snapshots.collateral_usd is
  'Залог по оракулу Aave (сумма total_collateral_usd по кошелькам и сетям) '
  'на момент съема. Тот же базис, что у debt_usd: LTV точки = debt_usd / '
  'collateral_usd. NULL = здоровье на эту дату не читалось.';

comment on column public.snapshots.health_factor is
  'МИНИМАЛЬНЫЙ health factor по (кошелек, сеть) на момент съема — '
  'ликвидация приходит к худшей позиции. NULL = долга нет («∞»), если '
  'debt_usd = 0, и «не читалось», если debt_usd тоже NULL.';
