-- =============================================================================
-- Привязка «займ → позиция» удалена вместе с таблицей.
--
-- Модель была неверной по существу: связь описывала отношение «этот займ
-- профинансировал эти позиции», но заём уходит в разные позиции ЧАСТЯМИ,
-- и доли нигде не хранились. Из-за этого «привязанный долг» считался
-- по целым займам: займ, разошедшийся на три позиции, целиком приписывался
-- каждой связке, а дельта «стоит ли позиция больше займа» сравнивала
-- несравнимое. Починить это без учёта долей нельзя, а доли — это уже
-- разметка позиции, которая живёт в position_marks (own/borrowed).
--
-- Разметка отвечает на тот же вопрос честнее: у каждой позиции указано,
-- сколько в ней своих денег и сколько заёмных. Сумма заёмных долей по всем
-- позициям и есть «куда ушёл долг», без выдуманного отношения один-к-одному.
--
-- Данных не теряем: на момент удаления таблица пуста.
--
-- Каскад в drop не нужен — на borrow_links никто не ссылается: обе её
-- колонки были внешними ключами НА protocol_positions, а не наоборот.
-- Политики RLS и гранты уходят вместе с таблицей.
-- =============================================================================

drop table if exists public.borrow_links;
