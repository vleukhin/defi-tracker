-- =============================================================================
-- Фаза 5: размещение заемных средств (Fluid, GMX v2 GM-пулы, Uniswap v3 LP).
--
-- Пробел, который закрывает фаза (docs/03-fazy-2-6.md):
--   «Активы» = три категории портфеля = залог BTC/ETH + ручные стейблы.
--   Заемные средства, размещенные в пулах и лендингах, туда не входили, а
--   «Долг» входил в формулу целиком — значит, Чистая = Активы − Долг была
--   ЗАНИЖЕНА ровно на размещенную заемную сумму. Читая позиции, мы делаем
--   утверждение методики «вычитание долга само корректно обрабатывает плечо»
--   действительно верным.
--
-- Разделение контуров сохраняется:
--   * три категории (доли, отклонения, цели) — только собственные средства,
--     содержимое пулов туда НЕ попадает;
--   * «Активы» пяти чисел = портфель + позиции.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- protocol_positions.protocol: добавляется 'fluid'. В исходной схеме были
-- заложены только aave_v3 / gmx_v2 / uni_v3 — Fluid в ТЗ не значился, но
-- именно там лежит депозит собственных и части заемных стейблов.
-- -----------------------------------------------------------------------------
alter table public.protocol_positions
  drop constraint protocol_positions_protocol_check;

alter table public.protocol_positions
  add constraint protocol_positions_protocol_check
  check (protocol in ('aave_v3', 'fluid', 'gmx_v2', 'uni_v3'));

-- Выборка «все позиции кошелька по протоколу» — горячий путь /api/positions
create index if not exists protocol_positions_wallet_protocol_idx
  on public.protocol_positions (wallet_id, protocol);

comment on column public.protocol_positions.value_usd is
  'Оценка на момент чтения (updated_at) для позиций, у которых цену дает сам '
  'протокол: GM-токен оценивает оракул GMX, у CoinGecko такой цены нет вовсе. '
  'Депозиты Fluid и LP-позиции оцениваются на показе по свежим ценам '
  'компонентов, поэтому у них колонка остается NULL.';

-- -----------------------------------------------------------------------------
-- chain_read_status.source: три новых источника. Деградируют независимо от
-- Aave и друг от друга — отказ GMX API не должен выглядеть как отказ Fluid.
-- -----------------------------------------------------------------------------
alter table public.chain_read_status
  drop constraint chain_read_status_source_check;

alter table public.chain_read_status
  add constraint chain_read_status_source_check
  check (source in ('aave_v3', 'aave_v3_debt', 'erc20', 'fluid', 'gmx_v2', 'uni_v3'));

-- -----------------------------------------------------------------------------
-- snapshots.positions_usd: вклад размещенных позиций в Активы на дату съема.
--
-- Пишется по той же причине, что и debt_usd: величина невосстановима задним
-- числом. Исторической цены GM-токена нет ни у GMX, ни у CoinGecko, а состав
-- LP-позиции зависит от тика пула в тот момент. Не сняли — потеряли навсегда.
--
-- NULL = стоимость позиций на момент съема известна не была («нет данных»,
-- а не «позиций не было»). total_usd при этом по-прежнему ТОЛЬКО портфель:
-- три категории ведутся по собственным средствам, и история их долей
-- не должна меняться задним числом от появления Фазы 5.
-- -----------------------------------------------------------------------------
alter table public.snapshots
  add column if not exists positions_usd numeric;

comment on column public.snapshots.positions_usd is
  'Размещенные позиции (Fluid после неттинга + GM + LP) на момент съема. '
  'Активы точки = total_usd + positions_usd. NULL = не было известно.';

-- -----------------------------------------------------------------------------
-- api_call_log.provider: GMX — новый внешний источник (arbitrum-api.gmxinfra.io,
-- бесплатный). Считаем его вызовы с первого дня, как и остальные (ТЗ §2).
-- -----------------------------------------------------------------------------
alter table public.api_call_log
  drop constraint api_call_log_provider_check;

alter table public.api_call_log
  add constraint api_call_log_provider_check
  check (provider in ('coingecko', 'alchemy', 'rpc', 'zerion', 'gmx'));

-- -----------------------------------------------------------------------------
-- borrow_links существует с Фазы 1 (init_schema) и менять его не требуется:
-- обе стороны ссылаются на protocol_positions.id, связь многие-ко-многим.
--
-- Семантика удаления намеренно каскадная: позиция закрыта или долг погашен —
-- строка protocol_positions удаляется читателем, и связка теряет смысл.
-- Привязка остается только бухгалтерской меткой и на расчет портфеля
-- по-прежнему не влияет (S5.3).
-- -----------------------------------------------------------------------------
comment on table public.borrow_links is
  'Ручная связь «займ → размещение» (S5.3). Только метка для экрана '
  '«Левередж»: на три категории портфеля и на пять чисел не влияет.';
