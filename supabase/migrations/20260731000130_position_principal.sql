-- =============================================================================
-- Фаза 6, уточнение: у позиции хранится ВЛОЖЕННОЕ, а не текущая доля.
--
-- Ошибка предыдущей версии: own_usd трактовался как «сколько в позиции своих
-- сейчас», и остаток стоимости выдавался за заемные средства. На депозите
-- Fluid это дало «заемных $295», хотя заемных там нет вовсе — 295 это
-- начисленные проценты на собственный депозит.
--
-- Остаток «стоимость − свои» может быть чем угодно: заемной частью,
-- начисленным доходом или убытком пула. Различить их вычитанием нельзя,
-- поэтому вложенное указывается двумя числами.
--
--   доход        = стоимость − (свое + заемное)
--   своя доля    = стоимость × свое / (свое + заемное)
--
-- Доход и убыток относятся на свое и заемное ПРОПОРЦИОНАЛЬНО вложенному:
-- капитал в пуле работает одинаково, чей бы он ни был.
-- =============================================================================

-- own_usd переименовывается: введенные значения и были «вложено своих»
alter table public.position_marks
  rename column own_usd to own_principal_usd;

alter table public.position_marks
  add column if not exists borrowed_principal_usd numeric
    check (borrowed_principal_usd is null or borrowed_principal_usd >= 0);

comment on column public.position_marks.own_principal_usd is
  'Сколько СОБСТВЕННЫХ средств вложено в позицию (не текущая доля). '
  'NULL = не размечено, и это не ноль.';

comment on column public.position_marks.borrowed_principal_usd is
  'Сколько ЗАЕМНЫХ средств вложено в позицию. NULL = не размечено. '
  'Заполняется по умолчанию НЕ нулем: ноль означал бы, что вложено только '
  'свое, а это утверждение, а не отсутствие данных.';

-- Заполнять borrowed_principal_usd автоматически нельзя. Позиция с
-- own_principal_usd = 0 означает «все заемное», но сколько именно вложено —
-- неизвестно; ноль там сказал бы «вложено ничего» и объявил доходом всю
-- стоимость позиции.
